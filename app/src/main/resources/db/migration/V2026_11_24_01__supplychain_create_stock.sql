CREATE TABLE stock_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id   BIGINT         NOT NULL,
    quantity        NUMERIC(12, 3) NOT NULL DEFAULT 0,
    alert_threshold NUMERIC(12, 3) NOT NULL DEFAULT 0,
    version         BIGINT         NOT NULL DEFAULT 0,
    updated_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_stock_item_ingredient FOREIGN KEY (ingredient_id) REFERENCES ingredient (id),
    CONSTRAINT uq_stock_item_ingredient UNIQUE (ingredient_id),
    CONSTRAINT ck_stock_item_quantity CHECK (quantity >= 0)
);

CREATE TABLE stock_movement (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT         NOT NULL,
    type          VARCHAR(20)    NOT NULL,
    delta         NUMERIC(12, 3) NOT NULL,
    reason        VARCHAR(255),
    created_at    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_stock_movement_ingredient FOREIGN KEY (ingredient_id) REFERENCES ingredient (id)
);

CREATE INDEX idx_stock_movement_ingredient ON stock_movement (ingredient_id, created_at);
