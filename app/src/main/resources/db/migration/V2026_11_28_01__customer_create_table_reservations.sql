CREATE TABLE table_reservations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id        BIGINT       NOT NULL,
    client_name      VARCHAR(120) NOT NULL,
    reservation_date DATE         NOT NULL,
    time_slot        VARCHAR(10)  NOT NULL,
    guests_count     INTEGER      NOT NULL,
    notes            VARCHAR(255),
    status           VARCHAR(20)  NOT NULL,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_table_reservations_guests CHECK (guests_count >= 1 AND guests_count <= 12),
    CONSTRAINT chk_table_reservations_status CHECK (status IN ('CONFIRMEE', 'ANNULEE'))
);

CREATE INDEX idx_table_reservations_date_slot
    ON table_reservations (reservation_date, time_slot);

CREATE INDEX idx_table_reservations_client_id
    ON table_reservations (client_id);