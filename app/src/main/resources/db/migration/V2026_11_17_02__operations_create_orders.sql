-- Domaine operations (Dev 2) — F6 Commandes et statuts
CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id        BIGINT        NOT NULL REFERENCES users (id),
    status           VARCHAR(20)   NOT NULL
        CHECK (status IN ('NOUVELLE', 'EN_PREPARATION', 'PRETE', 'LIVREE', 'RECUPEREE')),
    fulfillment_type VARCHAR(20)   NOT NULL CHECK (fulfillment_type IN ('LIVRAISON', 'RETRAIT')),
    total            NUMERIC(10, 2) NOT NULL,
    created_at       TIMESTAMP     NOT NULL,
    updated_at       TIMESTAMP     NOT NULL,
    version          BIGINT        NOT NULL DEFAULT 0
);
CREATE INDEX idx_orders_client ON orders (client_id);
CREATE INDEX idx_orders_status ON orders (status);

-- dish_id référence un plat du domaine supply chain : pas de clé étrangère entre domaines (voir README)
CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    dish_id    BIGINT         NOT NULL,
    dish_name  VARCHAR(150)   NOT NULL,
    quantity   INTEGER        NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL
);
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_dish ON order_items (dish_id);

CREATE TABLE order_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    from_status VARCHAR(20),
    to_status   VARCHAR(20) NOT NULL,
    changed_by  BIGINT      NOT NULL,
    changed_at  TIMESTAMP   NOT NULL
);
CREATE INDEX idx_order_status_history_order ON order_status_history (order_id);
