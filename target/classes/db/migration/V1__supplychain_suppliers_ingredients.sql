CREATE TABLE supplier (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150) NOT NULL,
    email      VARCHAR(150),
    phone      VARCHAR(30),
    address    VARCHAR(255),
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_supplier_name UNIQUE (name)
);

CREATE TABLE ingredient (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(150)   NOT NULL,
    unit        VARCHAR(20)    NOT NULL,
    unit_price  NUMERIC(10, 2) NOT NULL DEFAULT 0,
    supplier_id BIGINT         NOT NULL,
    CONSTRAINT fk_ingredient_supplier FOREIGN KEY (supplier_id) REFERENCES supplier (id),
    CONSTRAINT uq_ingredient_supplier_name UNIQUE (supplier_id, name)
);

CREATE INDEX idx_ingredient_supplier ON ingredient (supplier_id);
